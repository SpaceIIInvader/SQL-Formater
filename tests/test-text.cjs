'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { formatText } = require('../shared/desktop-worker.cjs');
const presetText = fs.readFileSync(path.join(__dirname, '../presets/preset_ibeexpert.ini'), 'utf8');
const text = 'SELECT "Name",\'Русский текст\' FROM t WHERE a=1; -- comment\r\n';
const before = text;
const result = formatText({ text, presetText });
assert.equal(text, before);
assert.ok(result.sql.includes('"Name"'));
assert.ok(result.sql.includes("'Русский текст'"));
assert.ok(result.sql.includes('-- comment'));
assert.ok(Array.isArray(result.unsupported));
assert.ok(Array.isArray(result.warnings));
assert.equal(formatText({ text: result.sql, presetText }).sql, result.sql);
assert.match(formatText({ text: 'select a from t;', presetText, caseMode: 2 }).sql, /SELECT/);
assert.match(formatText({ text: 'SELECT A FROM T;', presetText, caseMode: 1 }).sql, /select/);
assert.throws(() => formatText({ text: "select 'unclosed", presetText }));
assert.throws(() => formatText({ text: null, presetText }));
assert.throws(() => formatText({ text: ' '.repeat(2000001), presetText }));
assert.equal(formatText({ text: '', presetText }).sql, '');
console.log('PASS: text formatting, Unicode, quoted identifiers, comments, case override, idempotence, invalid SQL, type and size limits, empty input.');
